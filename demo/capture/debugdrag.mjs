import { chromium } from "playwright";
import path from "node:path";
import { fileURLToPath } from "node:url";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const br = await chromium.launch({ headless: true });
const ctx = await br.newContext({ storageState: path.join(HERE, "auth.json"), viewport: { width: 1920, height: 1080 } });
const page = await ctx.newPage();
page.on("response", (r) => { if (/_agent-native|\/api\//.test(r.url()) && r.request().method() !== "GET") console.log("RESP", r.status(), r.request().method(), r.url().slice(0, 120)); });
page.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text().slice(0, 200)); });
await page.goto("https://stigi.suitz.xyz/board", { waitUntil: "networkidle" });
await page.waitForTimeout(2000);
const src = page.locator("[data-note-id]", { hasText: "which plan am I even on?" }).first();
const zone = page.getByTestId("new-cluster-zone");
await src.scrollIntoViewIfNeeded();
await page.waitForTimeout(900);
const a = await src.boundingBox(); const z = await zone.boundingBox();
console.log("src", JSON.stringify(a), "zone", JSON.stringify(z));
await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2, { steps: 10 });
await page.mouse.down();
await page.mouse.move(a.x + a.width / 2 + 14, a.y + a.height / 2 + 14, { steps: 5 });
await page.waitForTimeout(300);
await page.mouse.move(z.x + z.width / 2, z.y + 60, { steps: 40 });
await page.waitForTimeout(500);
await page.screenshot({ path: "capture/debug-mid.png" });
console.log("overlay?", await page.evaluate(() => !!document.querySelector("[data-dnd-overlay], .stigi-note--overlay, [style*='position: fixed'][style*='transform']")));
await page.mouse.up();
await page.waitForTimeout(2500);
console.log(JSON.stringify(await page.evaluate(() => [...document.querySelectorAll("section[data-cluster-id]")].map((s) => s.dataset.clusterName + ":" + s.querySelectorAll("[data-note-id]").length))));
await page.screenshot({ path: "capture/debug-after.png" });
await ctx.close(); await br.close();
